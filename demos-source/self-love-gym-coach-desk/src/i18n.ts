export function translateUi(root: HTMLElement, language: Language) {
  document.documentElement.lang = language === 'es' ? 'es-419' : 'en';
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (!parent || ['SCRIPT', 'STYLE', 'TEXTAREA'].includes(parent.tagName)) continue;
    const current = node.textContent ?? '';
    const last = originals.get(node);
    const source = last && current === last.output ? last.source : current;
    if (parent.tagName === 'OPTION' && !parent.hasAttribute('value')) {
      parent.setAttribute('value', source.trim());
    }
    const output = language === 'es' ? translate(source) : source;
    originals.set(node, { source, output });
    if (current !== output) node.textContent = output;
  }
  for (const element of root.querySelectorAll('[placeholder], [aria-label], [title]')) {
    let entries = attrOriginals.get(element);
    if (!entries) { entries = new Map(); attrOriginals.set(element, entries); }
    for (const attribute of ['placeholder', 'aria-label', 'title']) {
      const current = element.getAttribute(attribute);
      if (current === null) continue;
      const last = entries.get(attribute);
      const source = last && current === last.output ? last.source : current;
      const output = language === 'es' ? translate(source) : source;
      entries.set(attribute, { source, output });
      if (current !== output) element.setAttribute(attribute, output);
    }
  }
}
