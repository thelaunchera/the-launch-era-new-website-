function safeHtml(value) {
  return String(value ?? '').replace(/[&<>"']/g, (char) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  }[char]));
}

const placements = {
  hero: [1],
  identity: [],
  palette: [],
  typography: [],
  pattern: [2],
  applications: [3, 4],
  universe: [5, 6, 7],
};

export function curatedGallery(brand, section) {
  const sources = EDITORIAL_PHOTO_SETS[brand.id] || [brand.heroPhoto, brand.detailPhoto].filter(Boolean);
  const indices = placements[section] || [];
  const chosen = indices.map(index => sources[index]).filter(Boolean);
  if (!chosen.length) return '';
  const titles = {hero: 'SECONDARY CAMPAIGN', pattern: 'MATERIAL STUDY', applications: 'APPLICATIONS', universe: 'VISUAL WORLD'};
  return '<div class="curated-gallery curated-gallery-' + section + '" aria-label="Fotografías aprobadas de ' + safeHtml(brand.name) + '">' +
    '<div class="curated-overline"><span>' + (titles[section] || 'PHOTOGRAPHY') + '</span><span>Original imagery · The Launch Era</span></div>' +
    '<div class="curated-grid">' + chosen.map((source, index) =>
      '<figure class="curated-frame"><img loading="lazy" decoding="async" src="' + safeHtml(source) +
      '" alt="Imagen de campaña original de ' + safeHtml(brand.name) + ', vista ' + (index + 1) +
      '" onerror="this.closest(\'figure\').style.display=\'none\'"><figcaption>' +
      safeHtml(brand.name) + ' / ' + String(index + 1).padStart(2, '0') + '</figcaption></figure>'
    ).join('') + '</div></div>';
}
