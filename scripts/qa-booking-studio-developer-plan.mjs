import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {planBookingBuild} from "../lib/booking-studio-developer-plan.mjs";
const fixture=JSON.parse(await readFile("fixtures/booking-studio-synthetic.json","utf8"));
const tenant=fixture.tenant_id;
const result=planBookingBuild(fixture,tenant);
assert.equal(result.ok,true);
assert.equal(result.tenant_id,tenant);
assert.equal(result.order_id,fixture.order_id);
assert.equal(result.publishable,false);
assert.equal(result.customer_notified,false);
assert.equal(result.preview_only,true);
assert.equal(result.blocked_integrations.length,7);
assert.equal(result.blocked_integrations.every(x=>x.state==="blocked_until_verified"),true);
assert.equal(planBookingBuild(fixture,"another-tenant").reason,"tenant_mismatch");
assert.equal(planBookingBuild({...fixture,stage:"research"},tenant).reason,"creative_handoff_required");
assert.equal(planBookingBuild({...fixture,design:{...fixture.design,photos:[]}},tenant).reason,"licensed_assets_required");
assert.equal(planBookingBuild({...fixture,client:{...fixture.client,services:[{name:"Standard",mode:"flat"}]}},tenant).reason,"verified_services_required");
assert.equal(planBookingBuild({...fixture,order_id:"../../other-tenant"},tenant).reason,"invalid_job");
assert.equal(planBookingBuild({...fixture,design:{...fixture.design,photos:[{url:"javascript:alert(1)",license:"fake",usage:"hero"}]}},tenant).reason,"licensed_assets_required");
console.log("Booking Studio AI Developer: 13 tenant, provenance, build and release gate assertions passed.");
