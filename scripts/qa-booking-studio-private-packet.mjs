import assert from "node:assert/strict";
import {mkdtemp,readFile,readdir,stat,rm,writeFile} from "node:fs/promises";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {spawnSync} from "node:child_process";
import {createHash} from "node:crypto";
const job=JSON.parse(await readFile("fixtures/booking-studio-synthetic.json","utf8"));
const root=await mkdtemp(join(tmpdir(),"tle-private-packet-test-"));
const command="scripts/build-booking-studio-private-packet.mjs";
const execute=(source,dest,tenant)=>spawnSync(process.execPath,[command,source,dest,tenant],{encoding:"utf8"});
try{
 const input=join(root,"job.json"),out=join(root,"private");
 await writeFile(input,JSON.stringify(job));
 let result=execute(input,out,job.tenant_id);
 assert.equal(result.status,0,result.stderr);
 const directories=await readdir(out);
 assert.equal(directories.length,1);
 assert.match(directories[0],/^tenant-[a-f0-9]{24}$/);
 assert.equal(directories[0].includes(job.tenant_id),false);
 const folder=join(out,directories[0]);
 assert.equal((await stat(folder)).mode&0o777,0o700);
 const files=(await readdir(folder)).sort();
 assert.deepEqual(files,["developer-plan.json","manifest.json","private-preview.html"]);
 for(const f of files)assert.equal((await stat(join(folder,f))).mode&0o777,0o600);
 const manifest=JSON.parse(await readFile(join(folder,"manifest.json"),"utf8"));
 const plan=JSON.parse(await readFile(join(folder,"developer-plan.json"),"utf8"));
 const html=await readFile(join(folder,"private-preview.html"),"utf8");
 assert.equal(manifest.published,false);
 assert.equal(manifest.customer_notified,false);
 assert.equal(manifest.release_approved,false);
 assert.equal(manifest.verified_functional_integrations,0);
 assert.equal(plan.publishable,false);
 assert.equal(plan.blocked_integrations.length,7);
 assert.equal(manifest.sha256_preview,createHash("sha256").update(html).digest("hex"));
 assert.match(html,/NO BOOKINGS ACCEPTED/);
 assert.doesNotMatch(html,/<form/i);
 assert.equal(execute(input,join(root,"bad"),"another-tenant").status,1);
 assert.equal(execute(input,out,job.tenant_id).status,1,"must never overwrite an existing customer packet");
 console.log("Booking Studio AI Developer private packet: 19 isolation, privacy and no-release assertions passed.");
}finally{await rm(root,{recursive:true,force:true})}
