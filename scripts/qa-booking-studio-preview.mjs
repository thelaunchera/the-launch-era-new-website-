import assert from "node:assert/strict";
import {createStudioJob,submitResearch,submitDesign} from "../lib/booking-studio-pipeline.mjs";
import {renderBookingStudioPreview} from "../lib/booking-studio-preview.mjs";
const input={verified_tenant_id:"synthetic-cleaner",order_id:"fake-order-001",payment_status:"paid",owner_start_approved:true,business_name:"Harbor House Cleaning",business_type:"residential cleaning",contact_email:"example@example.test",booking_policy:"Booking subject to confirmation",service_areas:["Miami"],services:[{name:"Recurring Home Cleaning",mode:"quote"},{name:"Deep Cleaning",mode:"flat",price:220}]};
let result=createStudioJob(input);assert.equal(result.ok,true);let job=result.job;
result=submitResearch(job,input.verified_tenant_id,{sources:[{url:"https://example.test/about",purpose:"Brand research"}],facts:[{claim:"Synthetic example business",source_url:"https://example.test/about"}]});assert.equal(result.ok,true);job=result.job;
const design={layout:"split",cards:"photographic",typography:"elegant",primary_color:"#191919",accent_color:"#B7DDF3",hero_title:"A fresh home, without the extra work.",hero_body:"Cleaning that makes more room for living.",design_rationale:"Synthetic visual direction",photos:[{url:"https://images.unsplash.com/photo-1581578731548-c64695cc6952",license:"Synthetic fixture only: must be checked before production",usage:"hero"}],section_order:["services","process","booking"]};
result=submitDesign(job,input.verified_tenant_id,design);assert.equal(result.ok,true);job=result.job;
const html=renderBookingStudioPreview(job);
assert.match(html,/Harbor House Cleaning/);
assert.match(html,/A fresh home, without the extra work/);
assert.match(html,/Deep Cleaning/);
assert.match(html,/\$220\.00/);
assert.match(html,/PRIVATE DESIGN PREVIEW/);
assert.match(html,/NO BOOKINGS ACCEPTED/);
assert.match(html,/noindex,nofollow,noarchive/);
assert.doesNotMatch(html,/<form\b/i);
assert.doesNotMatch(html,/<script\b/i);
assert.doesNotMatch(html,/supabase\.co|functions\/v1|cb-depot/i);
assert.match(html,/@media\(max-width:600px\)/);
assert.match(html,/hero split/);
const immersive={...job,design:{...job.design,layout:"immersive",cards:"tiles",typography:"modern"}};
assert.match(renderBookingStudioPreview(immersive),/hero immersive/);
assert.notEqual(renderBookingStudioPreview(immersive),html);
const attack={...job,client:{...job.client,business_name:'<script>alert("x")</script>'}};
assert.doesNotMatch(renderBookingStudioPreview(attack),/<script>alert/);
assert.match(renderBookingStudioPreview(attack),/&lt;script&gt;/);
assert.throws(()=>renderBookingStudioPreview({...job,design:null}),/Verified research/);
console.log("Booking Studio preview: 17 assertions passed.");
