import assert from "node:assert/strict";
import {createSyntheticBookingHarness} from "../lib/booking-studio-synthetic-integration.mjs";
const options={tenant_id:"tenant-a",services:[{name:"Standard",mode:"flat",price:120},{name:"Move out",mode:"quote"}],addons:[{name:"Oven",price:20}],service_areas:["Miami"],discounts:{weekly:10}};
const a=createSyntheticBookingHarness(options),b=createSyntheticBookingHarness({...options,tenant_id:"tenant-b"});
const base={tenant_id:"tenant-a",service_name:"Standard",service_area:"Miami",frequency:"weekly",customer_name:"Synthetic Person",customer_email:"synthetic@example.test",consent_to_contact:true,addons:["Oven"]};
assert.equal(a.synthetic_only,true);
assert.equal(a.submit({...base,tenant_id:"tenant-b"}).status,403);
assert.equal(a.submit({...base,service_area:"Boston"}).error,"outside_service_area");
assert.equal(a.submit({...base,consent_to_contact:false}).error,"contact_consent_required");
assert.equal(a.submit({...base,service_name:"Fake"}).error,"unknown_service");
assert.equal(a.submit({...base,addons:["Fake"]}).error,"unknown_addon");
assert.equal(a.submit({...base,addons:["Oven","Oven"]}).error,"duplicate_addon");
assert.equal(a.submit({...base,frequency:"daily"}).error,"invalid_frequency");
assert.equal(a.submit({...base,customer_email:"bad"}).error,"customer_details_required");
const booked=a.submit(base);
assert.equal(booked.ok,true);
assert.equal(booked.request.estimate,126);
assert.equal(booked.request.kind,"booking_request");
assert.equal(booked.request.confirmed,false);
assert.equal(booked.request.customer_notified,false);
assert.equal(booked.sent_email,false);
assert.equal(booked.published,false);
assert.equal(a.list("tenant-b").length,0);
assert.equal(b.list("tenant-b").length,0);
assert.equal(a.list("tenant-a").length,1);
const quoted=a.submit({...base,service_name:"Move out",addons:[],frequency:"one_time"});
assert.equal(quoted.request.kind,"quote_request");
assert.equal(quoted.request.estimate,null);
assert.equal(a.list("tenant-a").length,2);
assert.throws(()=>createSyntheticBookingHarness({...options,services:[{name:"Bad",mode:"flat",price:-1}]}),/Invalid synthetic services/);
console.log("Booking Studio synthetic integration: 22 tenant, pricing, consent, quote and no-side-effect assertions passed.");
